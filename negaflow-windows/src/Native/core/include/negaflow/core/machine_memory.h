#pragma once

// 이 기계의 메모리에서 나오는 값들입니다.
//
// **왜 필요한가** — 화상 버퍼 상한이 여러 곳에 `512MB` 라는 **바이트 상수**로 박혀 있었습니다.
// 48MP(8484×5656) 한 장이 float32 RGBA 로 **768MB** 라, 32GB 기계에서도 48MP 스캔을 아예
// 열지 못했습니다(`memory_limit_exceeded`). 상수는 메모리가 4GB 인 기계에서는 너무 크고
// 128GB 인 기계에서는 너무 작습니다 — 어느 쪽이든 거짓말입니다.
//
// 상한 자체는 그대로 둡니다. 손상된 TIFF 헤더가 20만×20만 을 주장하면 여전히 거부해야
// 합니다. 바뀌는 것은 **그 선을 어디서 얻는가** 뿐입니다.

#include <cstdint>

namespace negaflow::core {

/// 이 기계에 설치된 물리 메모리입니다. 못 읽으면 0 입니다.
[[nodiscard]] std::uint64_t installed_memory_bytes() noexcept;

/// <summary>화상 버퍼 하나가 커질 수 있는 상한입니다.</summary>
/// <remarks>
/// <para>
/// <b>이 기계에 설치된 물리 메모리 그대로입니다.</b> 그보다 큰 화상 한 장은 이 기계에서
/// 물리적으로 불가능하므로, 손상된 헤더를 거르는 목적은 그대로 지켜집니다. 반대로 그
/// 아래라면 <b>거부할 이유가 없습니다</b> — 실제로 잡히는지는 할당이 판정하고, 실패하면
/// <c>allocation_failed</c> 로 정직하게 돌아옵니다.
/// </para>
/// <para>
/// 분수를 두지 않는 이유: 1/4 로 잡으면 8GB 기계에서 128MP(2,048MB)가 아슬아슬하게 걸리고
/// 4GB 기계에서는 64MP 도 못 엽니다. 어떤 분모를 골라도 어느 기계에서는 거짓말이 됩니다.
/// 유일하게 기계와 무관하게 참인 선은 "설치 메모리보다 큰 것은 불가능" 하나뿐입니다.
/// </para>
/// <para>
/// 설치 메모리를 못 읽으면 예전 값인 512MB 로 갑니다 — 모르는 기계에서 예전보다 느슨해지지
/// 않게 합니다. 값은 프로세스에서 한 번만 읽습니다.
/// </para>
/// </remarks>
[[nodiscard]] std::uint64_t default_max_pixel_bytes() noexcept;

}  // namespace negaflow::core
